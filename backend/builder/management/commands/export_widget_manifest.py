# backend/builder/management/commands/export_widget_manifest.py
"""
Generates frontend/components/visualbuilder/WidgetMetadata.generated.js
from builder/services/frontend/react/writers/widget_manifest.py.

Run this after editing widget_manifest.py:

    python manage.py export_widget_manifest

CI should run it and fail the build if it produces a diff (see the
`test_widget_manifest_is_up_to_date` test in builder/tests.py) — that's
what actually prevents the frontend metadata from drifting out of sync
with the Python manifest, instead of relying on someone remembering to
re-run this by hand.
"""
import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from builder.services.frontend.react.writers.widget_manifest import (
    WIDGET_MANIFEST,
    CATEGORIES,
    DESIGN_TOKENS,
)

_HEADER = """// frontend/components/visualbuilder/WidgetMetadata.generated.js
// AUTO-GENERATED by `python manage.py export_widget_manifest`.
// Source of truth: backend/builder/services/frontend/react/writers/widget_manifest.py
// Do not hand-edit this file — your changes will be overwritten. Edit the
// Python manifest instead and regenerate.
"use client";

"""


class Command(BaseCommand):
    help = "Regenerate WidgetMetadata.generated.js from widget_manifest.py"

    def add_arguments(self, parser):
        parser.add_argument(
            "--out",
            default=None,
            help=(
                "Output path for the generated JS file. Defaults to "
                "<repo root>/frontend/components/visualbuilder/WidgetMetadata.generated.js "
                "(repo root is assumed to be BASE_DIR's parent — override with "
                "--out if your checkout uses a different layout)."
            ),
        )
        parser.add_argument(
            "--check",
            action="store_true",
            help="Don't write the file; exit non-zero if it would change (for CI).",
        )

    def handle(self, *args, **options):
        out_path = options["out"]
        if out_path:
            out_path = Path(out_path)
        else:
            out_path = (
                Path(settings.BASE_DIR).parent
                / "frontend"
                / "components"
                / "visualbuilder"
                / "WidgetMetadata.generated.js"
            )

        content = self._render_js()

        if options["check"]:
            existing = out_path.read_text(encoding="utf-8") if out_path.exists() else None
            if existing != content:
                self.stderr.write(self.style.ERROR(
                    f"{out_path} is out of date with widget_manifest.py. "
                    f"Run `python manage.py export_widget_manifest` and commit the result."
                ))
                raise SystemExit(1)
            self.stdout.write(self.style.SUCCESS("WidgetMetadata.generated.js is up to date."))
            return

        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"Wrote {out_path}"))

    def _render_js(self):
        # Strip the Python-only "render" spec for smart widgets (they have
        # no generic render spec) and keep it for generic ones, since the
        # frontend's GenericPreview needs it to mirror render_generic().
        widgets = {}
        for wtype, spec in WIDGET_MANIFEST.items():
            entry = {
                "category": spec["category"],
                "label": spec["label"],
                "icon": spec["icon"],
                "isContainer": spec["isContainer"],
                "defaultProps": spec["defaultProps"],
                "propsSchema": spec["propsSchema"],
                "tier": spec["tier"],
            }
            if spec["tier"] == "generic":
                entry["render"] = spec["render"]
            widgets[wtype] = entry

        widgets_json = json.dumps(widgets, indent=2, sort_keys=True)
        categories_json = json.dumps(CATEGORIES, indent=2)
        tokens_json = json.dumps(
            {k: v["value"] for k, v in DESIGN_TOKENS.items()}, indent=2, sort_keys=True
        )

        return (
            f"{_HEADER}"
            f"export const CATEGORIES = {categories_json};\n\n"
            f"export const WIDGET_METADATA = {widgets_json};\n\n"
            f"// Tailwind classes copied verbatim from the generated app's real\n"
            f"// components (visual_runtime.py, components.py, sidebar.py,\n"
            f"// visual_pages.py) so canvas previews for Table/Form/DetailView/\n"
            f"// StatCard/DataList/Tabs/Navbar/Sidebar/auth/RoleGate/automation\n"
            f"// widgets match the generated output instead of approximating it.\n"
            f"export const DESIGN_TOKENS = {tokens_json};\n"
        )
