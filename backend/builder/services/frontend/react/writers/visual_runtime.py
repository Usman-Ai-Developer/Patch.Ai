# backend/builder/services/frontend/react/writers/visual_runtime.py
"""
Writes the small runtime component library that pages generated by the
Visual Builder depend on (VisualBoundTable, VisualBoundForm, VisualBoundDetail,
VisualStatCard, VisualDataList, VisualTabs). These live in every generated
project under src/components/visual/ so visual pages have something real to
import — they are NOT copied from this repo's own frontend, they are written
fresh into each generated project, exactly like every other writer module.

This is only ever called when at least one page actually uses a visual
layout (see generator.py), so projects that don't use the Visual Builder
never get these extra files.
"""

_VISUAL_DATA_WIDGETS = r'''// src/components/visual/VisualDataWidgets.jsx
// Shared runtime components used by pages generated from the Visual Builder.
// These are plain React components (no TypeScript) so they work regardless
// of how strict the project's build config is, and they reuse the SAME
// axios client (`src/api/client`) as every other generated page, so auth,
// token refresh, and base URL behave identically everywhere in the app.
import React, { useEffect, useState, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import api from '../../api/client';

// ─── Table bound to a model's list endpoint ────────────────────────────────
export function VisualBoundTable({ endpoint, columns, showActions = true, editBasePath }) {
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const load = useCallback(() => {
    setLoading(true);
    api
      .get(endpoint)
      .then((res) => {
        const data = Array.isArray(res.data) ? res.data : res.data?.results || [];
        setRows(data);
        setError(null);
      })
      .catch((err) => setError(err.message || 'Failed to load data'))
      .finally(() => setLoading(false));
  }, [endpoint]);

  useEffect(() => {
    load();
  }, [load]);

  const handleDelete = async (id) => {
    if (!window.confirm('Delete this record?')) return;
    try {
      await api.delete(`${endpoint}${id}/`);
      load();
    } catch (err) {
      // eslint-disable-next-line no-alert
      alert(err.message || 'Failed to delete record');
    }
  };

  if (loading) return <div className="p-4 text-sm text-subtext">Loading…</div>;
  if (error) return <div className="p-4 text-sm text-red-500">{error}</div>;

  return (
    <div className="overflow-x-auto">
      <table className="min-w-full bg-panel border border-line rounded-lg">
        <thead>
          <tr className="border-b border-line">
            {columns.map((col) => (
              <th key={col.key} className="px-4 py-2 text-left text-sm font-medium text-subtext">
                {col.label}
              </th>
            ))}
            {showActions && <th className="px-4 py-2 text-left text-sm font-medium text-subtext">Actions</th>}
          </tr>
        </thead>
        <tbody>
          {rows.length === 0 && (
            <tr>
              <td colSpan={columns.length + (showActions ? 1 : 0)} className="px-4 py-6 text-center text-subtext text-sm">
                No records yet.
              </td>
            </tr>
          )}
          {rows.map((item) => (
            <tr key={item.id} className="border-b border-line/50 hover:bg-surface-container/50">
              {columns.map((col) => (
                <td key={col.key} className="px-4 py-2 text-sm">
                  {String(item[col.key] ?? '')}
                </td>
              ))}
              {showActions && (
                <td className="px-4 py-2">
                  <div className="flex gap-2">
                    <a href={`${editBasePath}/${item.id}/edit`} className="text-brand-100 hover:underline text-sm">
                      Edit
                    </a>
                    <button
                      type="button"
                      onClick={() => handleDelete(item.id)}
                      className="text-red-500 hover:underline text-sm"
                    >
                      Delete
                    </button>
                  </div>
                </td>
              )}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

// ─── Auto-generated create/edit form bound to a model ──────────────────────
export function VisualBoundForm({ endpoint, mode = 'create', fields, redirectTo }) {
  const navigate = useNavigate();
  const [values, setValues] = useState(() =>
    fields.reduce((acc, f) => ({ ...acc, [f.name]: f.type === 'checkbox' ? false : '' }), {})
  );
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState(null);

  const handleChange = (name, type) => (e) => {
    const value = type === 'checkbox' ? e.target.checked : e.target.value;
    setValues((prev) => ({ ...prev, [name]: value }));
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setSubmitting(true);
    setError(null);
    try {
      if (mode === 'edit' && values.id) {
        await api.patch(`${endpoint}${values.id}/`, values);
      } else {
        await api.post(endpoint, values);
      }
      if (redirectTo) navigate(redirectTo);
    } catch (err) {
      setError(err.response?.data ? JSON.stringify(err.response.data) : err.message || 'Failed to save');
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <form onSubmit={handleSubmit} className="space-y-4 max-w-lg">
      {fields.map((f) => (
        <div key={f.name} className="flex flex-col gap-1">
          <label className="text-sm font-medium text-subtext" htmlFor={f.name}>
            {f.label}
            {f.required && <span className="text-red-500"> *</span>}
          </label>
          {f.type === 'checkbox' ? (
            <input
              id={f.name}
              type="checkbox"
              checked={!!values[f.name]}
              onChange={handleChange(f.name, f.type)}
              className="h-4 w-4"
            />
          ) : (
            <input
              id={f.name}
              type={f.type}
              required={f.required}
              value={values[f.name] ?? ''}
              onChange={handleChange(f.name, f.type)}
              className="bg-surface border border-line rounded-lg px-3 py-2 text-sm outline-none focus:border-brand-100"
            />
          )}
        </div>
      ))}
      {error && <div className="text-sm text-red-500">{error}</div>}
      <button
        type="submit"
        disabled={submitting}
        className="px-4 py-2 rounded-lg font-medium bg-brand-100 text-white hover:opacity-90 disabled:opacity-40"
      >
        {submitting ? 'Saving…' : mode === 'edit' ? 'Save Changes' : 'Create'}
      </button>
    </form>
  );
}

// ─── Read-only detail view bound to a model's retrieve endpoint ────────────
export function VisualBoundDetail({ endpoint, fields }) {
  const [item, setItem] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    // endpoint here is the list endpoint; the record id is read from the URL
    // by the page that embeds this widget in typical model detail pages.
    const parts = window.location.pathname.split('/').filter(Boolean);
    const id = parts[parts.length - 1];
    api
      .get(`${endpoint}${id}/`)
      .then((res) => setItem(res.data))
      .finally(() => setLoading(false));
  }, [endpoint]);

  if (loading) return <div className="p-4 text-sm text-subtext">Loading…</div>;
  if (!item) return <div className="p-4 text-sm text-subtext">Not found</div>;

  return (
    <div className="bg-surface border border-line rounded-lg p-4 space-y-2">
      {fields.map((key) => (
        <div key={key} className="flex justify-between border-b border-line/40 py-1 text-sm">
          <span className="text-subtext capitalize">{key}</span>
          <span>{String(item[key] ?? '')}</span>
        </div>
      ))}
    </div>
  );
}

// ─── Simple stat card bound to a model's count ─────────────────────────────
export function VisualStatCard({ label, endpoint }) {
  const [count, setCount] = useState(null);

  useEffect(() => {
    api
      .get(endpoint)
      .then((res) => {
        const data = res.data;
        if (Array.isArray(data)) setCount(data.length);
        else if (typeof data?.count === 'number') setCount(data.count);
        else setCount(Array.isArray(data?.results) ? data.results.length : 0);
      })
      .catch(() => setCount(null));
  }, [endpoint]);

  return (
    <div className="bg-surface border border-line rounded-lg p-4">
      <div className="text-2xl font-bold">{count === null ? '—' : count}</div>
      <div className="text-sm text-subtext">{label}</div>
    </div>
  );
}

// ─── Simple linked list bound to a model ───────────────────────────────────
export function VisualDataList({ endpoint, titleField, linkBasePath }) {
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    api
      .get(endpoint)
      .then((res) => setRows(Array.isArray(res.data) ? res.data : res.data?.results || []))
      .finally(() => setLoading(false));
  }, [endpoint]);

  if (loading) return <div className="p-4 text-sm text-subtext">Loading…</div>;

  return (
    <ul className="divide-y divide-line">
      {rows.map((item) => (
        <li key={item.id} className="py-2">
          <a href={`${linkBasePath}/${item.id}`} className="hover:text-brand-100">
            {String(item[titleField] ?? `#${item.id}`)}
          </a>
        </li>
      ))}
      {rows.length === 0 && <li className="py-2 text-sm text-subtext">No records yet.</li>}
    </ul>
  );
}
'''

_VISUAL_TABS = r'''// src/components/visual/VisualTabs.jsx
// Minimal tab container used by pages built with the Visual Builder's Tabs widget.
import React, { useState } from 'react';

export default function VisualTabs({ labels, children }) {
  const [active, setActive] = useState(0);
  return (
    <div>
      <div className="flex gap-2 border-b border-line mb-4">
        {labels.map((label, idx) => (
          <button
            key={label}
            type="button"
            onClick={() => setActive(idx)}
            className={`px-4 py-2 text-sm font-medium border-b-2 transition-colors ${
              active === idx ? 'border-brand-100 text-brand-100' : 'border-transparent text-subtext hover:text-text'
            }`}
          >
            {label}
          </button>
        ))}
      </div>
      <div>{typeof children === 'function' ? children(active) : children}</div>
    </div>
  );
}
'''


def write_visual_runtime(components_dir):
    visual_dir = components_dir / "visual"
    visual_dir.mkdir(parents=True, exist_ok=True)
    (visual_dir / "VisualDataWidgets.jsx").write_text(_VISUAL_DATA_WIDGETS, encoding="utf-8")
    (visual_dir / "VisualTabs.jsx").write_text(_VISUAL_TABS, encoding="utf-8")
    return [str(visual_dir / "VisualDataWidgets.jsx"), str(visual_dir / "VisualTabs.jsx")]
